-- Migration 0002: fixes from the schema review (issue #12).
-- Apply after 0001, only when schema_migration has no row for version 2.

PRAGMA foreign_keys = ON;

-- A deal that leaves WON or LOST is open again: clear what closing set.
CREATE TRIGGER deal_reopen_upd AFTER UPDATE OF stage ON deal
WHEN NEW.stage NOT IN ('WON', 'LOST') AND (NEW.closed_at IS NOT NULL OR NEW.total_deal_time IS NOT NULL)
BEGIN
    UPDATE deal SET closed_at = NULL, total_deal_time = NULL WHERE id = NEW.id;
END;

-- duration_ms follows the timestamps both ways: NULL again when either is cleared.
DROP TRIGGER ai_run_duration_upd;
CREATE TRIGGER ai_run_duration_upd AFTER UPDATE OF started_at, finished_at ON ai_run
BEGIN
    UPDATE ai_run
       SET duration_ms = CASE WHEN NEW.started_at IS NOT NULL AND NEW.finished_at IS NOT NULL
               THEN CAST(ROUND((julianday(NEW.finished_at) - julianday(NEW.started_at)) * 86400000) AS INTEGER) END
     WHERE id = NEW.id;
END;

-- Foreign keys that had no index: deleting a parent scanned the whole child table.
CREATE INDEX activity_contact_idx ON activity(contact_id);
CREATE INDEX activity_deal_idx ON activity(deal_id);
CREATE INDEX enrichment_ai_run_idx ON enrichment_fact(ai_run_id);
CREATE INDEX rubric_answer_run_idx ON rubric_answer(ai_run_id);

