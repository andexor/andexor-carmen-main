"""Generate PlantUML entity-relationship diagrams from the built schema.

Reads every migration in db/carmen (in order) and writes doc/uml/erd-*.puml:
  erd-summary.puml   every table as a block, a line wherever a foreign key joins two tables
  erd-<table>.puml   one per table: that table with all its columns, and the tables it
                     references or that reference it

Run from the repo root (build_schema.sh does this). check_schemas.py fails if the files are stale.
"""

import pathlib
import sqlite3
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "doc" / "uml"
sys.path.insert(0, str(ROOT / "tools"))
import build_schema  # noqa: E402

Row = dict[str, Any]  # one column or one foreign key
Cols = dict[str, list[Row]]
Srt = dict[tuple[str, str], str]

HEADER = (
    "' SPDX-License-Identifier: Apache-2.0\n"
    "' Copyright 2026 Andexor Network, Inc.\n"
    "' Author: Ed Jenkins <ed@andexor.net>\n"
    "' Generated by tools/gen_erd.py from the migrations in db/carmen. Do not edit by hand.\n"
)
STYLE = "hide circle\nskinparam nodesep 40\nskinparam ranksep 60\n"


def load() -> tuple[list[str], Cols, list[Row], Srt]:
    con = sqlite3.connect(":memory:")
    for p in sorted(build_schema.DB.glob("[0-9][0-9][0-9][0-9]_*.sql")):
        if not p.name.endswith(".base.sql"):
            con.executescript(p.read_text())
    tables: list[str] = [r[0] for r in con.execute("select name from sqlite_master where type='table' and name not like 'sqlite_%' order by name")]
    cols: Cols = {}
    rels: list[Row] = []
    for t in tables:
        cols[t] = [dict(name=r[1], type=r[2] or "", notnull=bool(r[3]), pk=r[5]) for r in con.execute(f"pragma table_info({t})")]
        notnull = {c["name"]: c["notnull"] for c in cols[t]}
        for fk in con.execute(f"pragma foreign_key_list({t})"):
            rels.append(dict(child=t, col=fk[3], parent=fk[2], pcol=fk[4], nullable=not notnull[fk[3]]))
    srt: Srt = {}
    for base in build_schema.bases():
        for t, c, d in build_schema.srt_columns(base.read_text()):
            srt[(t, c)] = d
    return tables, cols, rels, srt


def line(rel: Row, label: bool) -> str:
    end = "o|" if rel["nullable"] else "||"
    text = f"{rel['child']} }}o--{end} {rel['parent']}"
    return f"{text} : {rel['col']}" if label else text


def entity(table: str, cols: Cols, rels: list[Row], srt: Srt, shown: set[str] | None) -> str:
    """An entity block. shown is None for every column, or the set of column names to list."""
    fks = {r["col"] for r in rels if r["child"] == table}
    pks = sorted((c for c in cols[table] if c["pk"]), key=lambda c: c["pk"])
    rest = [c for c in cols[table] if not c["pk"] and (shown is None or c["name"] in shown)]

    def row(c: Row) -> str:
        tags: list[str] = []
        if c["pk"]:
            tags.append("<<PK>>")
        if c["name"] in fks:
            tags.append("<<FK>>")
        if (table, c["name"]) in srt:
            tags.append(f"<<SRT {srt[(table, c['name'])]}>>")
        mark = "* " if c["pk"] or c["notnull"] else "  "
        return f"  {mark}{c['name']} : {c['type']} {' '.join(tags)}".rstrip()

    out = [f"entity {table} {{"]
    out += [row(c) for c in pks]
    if pks and rest:
        out.append("  --")
    out += [row(c) for c in rest]
    out.append("}")
    return "\n".join(out)


def render_all() -> dict[str, str]:
    tables, cols, rels, srt = load()
    files: dict[str, str] = {}

    body = [f"entity {t}" for t in tables] + [""] + [line(r, False) for r in rels]
    files["erd-summary.puml"] = (
        HEADER + "@startuml erd-summary\ntitle Carmen data model: tables and relationships\n" + STYLE + "hide empty members\n\n" + "\n".join(body) + "\n@enduml\n"
    )

    for t in tables:
        mine = [r for r in rels if r["child"] == t or r["parent"] == t]
        related = sorted({r["child"] for r in mine} | {r["parent"] for r in mine} | {t})
        blocks: list[str] = []
        for o in related:
            if o == t:
                shown: set[str] | None = None
            else:
                shown = set()
                for r in mine:
                    if r["child"] == o:
                        shown.add(r["col"])
                    if r["parent"] == o:
                        shown.add(r["pcol"])
            blocks.append(entity(o, cols, rels, srt, shown))
        lines = [line(r, True) for r in mine]
        files[f"erd-{t}.puml"] = (
            HEADER + f"@startuml erd-{t}\ntitle {t} and the tables related to it\n" + STYLE + "\n" + "\n\n".join(blocks) + ("\n\n" + "\n".join(lines) if lines else "") + "\n@enduml\n"
        )
    return files


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("erd-*.puml"):
        old.unlink()
    files = render_all()
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"Wrote {len(files)} diagrams to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
