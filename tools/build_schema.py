"""Build db/carmen/NNNN_name.sql from each NNNN_name.base.sql plus System Reference Table (SRT)
triggers. A column gets triggers when its definition carries a "-- SRT domain: X" comment, either in
a CREATE TABLE or on an ALTER TABLE ... ADD COLUMN line, and only the file that declares it generates
them. A migration already on main is never rebuilt. Run from the repo root."""
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
DB = ROOT / "db" / "carmen"

TRIGGERS = """CREATE TRIGGER srt_{t}_{c}_ins BEFORE INSERT ON {t}
WHEN NEW.{c} IS NOT NULL AND NOT EXISTS (SELECT 1 FROM srt WHERE domain='{d}' AND code=NEW.{c} AND active=1)
BEGIN SELECT RAISE(ABORT, 'SRT violation: {t}.{c} not in {d}'); END;
CREATE TRIGGER srt_{t}_{c}_upd BEFORE UPDATE OF {c} ON {t}
WHEN NEW.{c} IS NOT NULL AND NEW.{c} IS NOT OLD.{c} AND NOT EXISTS (SELECT 1 FROM srt WHERE domain='{d}' AND code=NEW.{c} AND active=1)
BEGIN SELECT RAISE(ABORT, 'SRT violation: {t}.{c} not in {d}'); END;
"""
FOOTER = (
    "\n-- ---------------------------------------------------------------------------\n"
    "-- SRT enforcement triggers (generated by tools/build_schema.py from the\n"
    "-- \"-- SRT domain:\" comments in this file; never edit by hand).\n"
    "-- ---------------------------------------------------------------------------\n"
)


def srt_columns(text):
    """(table, column, domain) for every SRT-commented column definition, in file order."""
    out, table = [], None
    for line in text.splitlines():
        m = re.match(r"\s*CREATE TABLE (\w+)", line)
        if m:
            table = m.group(1)
            continue
        a = re.match(r"\s*ALTER TABLE (\w+) ADD COLUMN (\w+)\s.*--\s*SRT domain: ([A-Z_]+)", line)
        if a:
            out.append(a.groups())
            continue
        c = re.match(r"\s+(\w+)\s+(?:TEXT|INTEGER|REAL|BLOB|NUMERIC)\b.*--\s*SRT domain: ([A-Z_]+)", line)
        if c and table:
            out.append((table, c.group(1), c.group(2)))
    return out


def build(base_text):
    cols = srt_columns(base_text)
    if not cols:
        return base_text
    return base_text.rstrip("\n") + "\n" + FOOTER + "\n" + "\n".join(TRIGGERS.format(t=t, c=c, d=d) for t, c, d in cols)


def bases():
    return sorted(DB.glob("[0-9][0-9][0-9][0-9]_*.base.sql"))


def built(base):
    return base.with_name(base.name.replace(".base.sql", ".sql"))


def frozen():
    """(ref, paths): the SQL files already on main, which must never change."""
    for ref in ("origin/main", "HEAD"):
        r = subprocess.run(["git", "ls-tree", "-r", "--name-only", ref, "--", "db/carmen"], cwd=ROOT, capture_output=True, text=True)
        if r.returncode == 0:
            return ref, set(r.stdout.split())
    return None, set()


def main():
    ref, paths = frozen()
    for base in bases():
        out = built(base)
        rel = out.relative_to(ROOT).as_posix()
        if rel in paths:
            print(f"kept   {rel} (already on {ref})")
            continue
        out.write_text(build(base.read_text()))
        print(f"wrote  {rel}")


if __name__ == "__main__":
    main()
